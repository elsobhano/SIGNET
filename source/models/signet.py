class SignetGate(nn.Module):
    def __init__(self, args, num_experts=2, k=2):
        super().__init__()
        self.args = args
        self.num_experts = num_experts
        self.k = k
        
        self.modes = ['body', 'left', 'right', 'face_all']
        # hidden_dim = 512 * 2
        
        # # Router network (projects global pooled features to logits over experts)
        # self.router = nn.Sequential(
        # nn.Linear(hidden_dim, 128),
        # nn.ReLU(),
        # nn.Linear(128, num_experts)
        # )
        hidden_dim = 512  # size of each x_global from expert

        # Router remains the same
        self.router = nn.Sequential(
            nn.Linear(hidden_dim, 128),
            nn.ReLU(),
            nn.Linear(128, num_experts)
        )
        
        # Learnable query for attention aggregation
        # self.gate_query = nn.Parameter(torch.randn(1, 1, hidden_dim)) # this is for the static router
        self.query_mlp = nn.Sequential(
            nn.Linear(hidden_dim, hidden_dim),
            nn.ReLU(),
            nn.Linear(hidden_dim, hidden_dim)
        )
        self.gate_norm = nn.LayerNorm(hidden_dim)
        
        # adding expert adapter
        self.adapters = nn.ModuleList([
            ExpertAdapter(hidden_dim=768, rank=16, dropout=0.1)
            for _ in range(num_experts)
            ])

        
        
        self.apply(self._init_weights)
        
        if "CSL" in self.args.dataset:
            self.lang = 'Chinese'
        elif "Phoenix" in self.args.dataset or "DGS" in self.args.dataset:
            self.lang = 'German'
        else:
            self.lang = 'English'
        
        self.mt5_model = MT5ForConditionalGeneration.from_pretrained(mt5_path)
        self.mt5_tokenizer = T5Tokenizer.from_pretrained(mt5_path, legacy=False)
        


        if args.use_lora:
            lora_config = LoraConfig(
                            r=args.lora_rank,                         # Rank
                            lora_alpha=args.lora_alpha,               # Scaling factor
                            target_modules=["q", "v"],                # LoRA target layers
                            lora_dropout=args.lora_dropout,
                            bias="none",
                            task_type=TaskType.SEQ_2_SEQ_LM
                        )
            self.mt5_model = get_peft_model(self.mt5_model, lora_config)
            # 1 Freeze everything first
            for param in self.mt5_model.parameters():
                param.requires_grad = False

            # 2 Unfreeze only encoder LoRA parameters
            for name, param in self.mt5_model.named_parameters():
                if "lora" in name and "encoder" in name:
                    param.requires_grad = True

            # 3 Unfreeze only the *base* decoder parameters (not LoRA)
            for name, param in self.mt5_model.named_parameters():
                if "decoder" in name and "lora" not in name:
                    param.requires_grad = True
    
        
    def _init_weights(self, m):
        if isinstance(m, nn.Linear):
            trunc_normal_(m.weight, std=.02)
            if isinstance(m, nn.Linear) and m.bias is not None:
                nn.init.constant_(m.bias, 0)
        elif isinstance(m, nn.LayerNorm):
            nn.init.constant_(m.bias, 0)
            nn.init.constant_(m.weight, 1.0)

    def maybe_autocast(self, dtype=torch.float32):
        # if on cpu, don't use autocast
        # if on gpu, use autocast with dtype if provided, otherwise use torch.float16
        # enable_autocast = self.device != torch.device("cpu")
        enable_autocast = True

        if enable_autocast:
            return torch.cuda.amp.autocast(dtype=dtype)
        else:
            return contextlib.nullcontext()

    def topk_gating(self, x_global, expert_outputs, temperature=1.0):
        """x_global: [B, D] global summary"""
        # print(x_global.shape)
        logits = self.router(x_global)  # [B, num_experts]

        if self.training:
            # print("Using stochastic Gumbel-Softmax gating during training.")
            # Training: stochastic Gumbel-Softmax
            weights = F.gumbel_softmax(logits, tau=temperature, hard=False)  # [B, num_experts]
            
            # Weighted mixture of all experts (encourages exploration)
            fused = 0
            for i, expert in enumerate(expert_outputs):
                w = weights[:, i].unsqueeze(-1).unsqueeze(-1)  # [B,1,1]
                fused = fused + w * expert
            topk_idx = torch.topk(logits, self.k, dim=-1).indices  # just for monitoring
        else:
            # Evaluation: deterministic Top-k
            topk_vals, topk_idx = torch.topk(logits, self.k, dim=-1)  # [B, k]
            gate_weights = F.softmax(topk_vals, dim=-1)               # [B, k]

            B, T, H = expert_outputs[0].shape
            fused = torch.zeros(B, T, H, device=expert_outputs[0].device)

            for i in range(self.k):
                idx = topk_idx[:, i]   # [B]
                w = gate_weights[:, i] # [B]
                # Batch gather: select embeddings from expert_outputs[idx[b]] for each b
                selected = torch.stack([expert_outputs[j][b] for b, j in enumerate(idx)], dim=0)
                fused += w.unsqueeze(-1).unsqueeze(-1) * selected

            weights = gate_weights  # [B, k]

        return fused, topk_idx, weights
    
    def aggregate_experts_attention_static(self, expert_globals):
        """expert_globals: [B, N, D]"""
        B, N, D = expert_globals.shape

        # Broadcast the learnable query
        query = self.gate_query.expand(B, 1, D)  # [B, 1, D]

        # Compute attention over experts
        attn_logits = (query @ expert_globals.transpose(1, 2)) / math.sqrt(D)  # [B, 1, N]
        attn_weights = torch.softmax(attn_logits, dim=-1)                      # [B, 1, N]

        # Weighted combination of expert globals
        x_global = (attn_weights @ expert_globals).squeeze(1)                  # [B, D]

        # Normalize output for stability
        x_global = self.gate_norm(x_global)
        return x_global, attn_weights
    
    
    def aggregate_experts_attention(self, expert_globals):
        """Aggregate multiple expert-level global features into a single vector using"""
        B, N, D = expert_globals.shape

        # Create data-dependent query
        # Query is computed from the mean expert feature per sample.
        avg_global = expert_globals.mean(dim=1)  # [B, D]
        query = self.query_mlp(avg_global).unsqueeze(1)  # [B, 1, D]

        # Compute attention logits
        attn_logits = torch.bmm(query, expert_globals.transpose(1, 2))  # [B, 1, N]
        attn_logits = attn_logits / math.sqrt(D)

        # Optional: normalize for numerical stability
        attn_logits = attn_logits - attn_logits.max(dim=-1, keepdim=True)[0]

        # Softmax across experts
        attn_weights = torch.softmax(attn_logits, dim=-1)  # [B, 1, N]
        attn_weights = F.dropout(attn_weights, p=0.1, training=self.training)

        # Weighted sum of expert globals
        x_global = torch.bmm(attn_weights, expert_globals).squeeze(1)  # [B, D]

        # Normalize for stability
        x_global = self.gate_norm(x_global)

        return x_global, attn_weights.squeeze(1)
    
    def forward(
        self,
        inputs_of_experts,
        tgt_input,
        input_attention_mask,
        task="SLT",
        **kwargs
    ):
        if task == "contrastive_loss":
            return self._forward_contrastive(inputs_of_experts, tgt_input, input_attention_mask, **kwargs)
        elif task == "contrastive_ablation_loss":
            return self._forward_contrastive_ablation(inputs_of_experts, tgt_input, input_attention_mask, **kwargs)
        elif task == "sinkhorn_loss":
            return self._forward_sinkhorn(inputs_of_experts, tgt_input, input_attention_mask, **kwargs)
        elif task == "SLT":
            return self._forward_translation(inputs_of_experts, tgt_input, input_attention_mask, **kwargs)
        elif task == "ablation_SLT":
            return self._forward_ablation(inputs_of_experts, tgt_input, input_attention_mask, **kwargs) 
        else:
            raise ValueError(f"Unknown task type: {task}")
        
    def _forward_contrastive(self, inputs_of_experts, tgt_input, input_attention_mask, temperature=1.0, contrastive_weight=1.0):
        """inputs_of_experts: list of dicts from experts"""

        # 1 Gating Fusion
        # globals = [exp['x_global'] for exp in inputs_of_experts] # list of [B, D]
        # x_global = torch.cat(globals, dim=-1) # [B, num_experts*D]
        expert_globals = torch.stack([exp['x_global'] for exp in inputs_of_experts], dim=1)  # [B, N, D]
        # expert_outputs = [exp['encoder_embeds'] for exp in inputs_of_experts] # list of [B, T, H]
        expert_outputs = []
        for i, exp in enumerate(inputs_of_experts):
            out = exp['encoder_embeds']          # [B, T, H]
            adapted_out = self.adapters[i](out)  # apply LoRA-style adapter
            expert_outputs.append(adapted_out)
        
        # Attention-based aggregation
        x_global, attn_weights = self.aggregate_experts_attention(expert_globals)  # [B, D]

        fused_embeds, topk_idx, gate_weights = self.topk_gating(x_global, expert_outputs)
        inputs_embeds = fused_embeds  # [B, T, H]

        # 2 Get text embeddings (precomputed)
        text_embeds = tgt_input["text_embeddings"].to(inputs_embeds.device).float()  # [B, H]

        # 3 Pass video embeddings through mT5 encoder
        # The goal is to align the *encoded* video features with text embeddings
        video_encoded_out = self.mt5_model.encoder(
            inputs_embeds=inputs_embeds,
            attention_mask=input_attention_mask,
            return_dict=True
        )
        video_encoded = video_encoded_out.last_hidden_state.mean(dim=1)  # [B, H]

        # 4 Normalize both for contrastive alignment
        video_encoded = F.normalize(video_encoded, dim=-1)
        text_embeds = F.normalize(text_embeds, dim=-1)

        # 5 Learnable temperature scaling
        if not hasattr(self, "logit_scale"):
            self.logit_scale = torch.nn.Parameter(torch.ones([]) * np.log(1 / 0.07))
        scale = self.logit_scale.exp()

        # 6 Compute similarity matrix
        # Ensure both are same dtype (use video_encoded's dtype)
        text_embeds = text_embeds.to(video_encoded.dtype)
        logits_per_video = (video_encoded @ text_embeds.t()) * scale
        logits_per_text = logits_per_video.t()
        targets = torch.arange(len(video_encoded), device=video_encoded.device)

        contrastive_loss = (
            F.cross_entropy(logits_per_video, targets) +
            F.cross_entropy(logits_per_text, targets)
        ) / 2

        # 9 Return outputs
        stack_out = {
            "contrastive_loss": contrastive_loss,
            "loss": contrastive_loss,
        }

        return stack_out
    
    def _forward_contrastive_ablation(self, inputs_of_experts, tgt_input, input_attention_mask, temperature=1.0, contrastive_weight=1.0):
        """inputs_of_experts: list of dicts from experts"""

