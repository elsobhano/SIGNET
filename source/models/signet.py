class ExpertAdapter(nn.Module):
    """Lightweight LoRA-style adapter applied after frozen expert outputs."""
    def __init__(self, hidden_dim, rank=16, dropout=0.1):
        super().__init__()
        self.norm = nn.LayerNorm(hidden_dim)
        self.dropout = nn.Dropout(dropout)
        
        # Low-rank decomposition (A down, B up)
        self.A = nn.Linear(hidden_dim, rank, bias=False)
        self.B = nn.Linear(rank, hidden_dim, bias=False)

        # Initialize near-zero so residual dominates at start
        nn.init.normal_(self.A.weight, std=1e-4)
        nn.init.zeros_(self.B.weight)

    def forward(self, x):
        """x: [B, T, H] or [B, H]"""
        residual = x
        x = self.norm(x)
        delta = self.B(self.A(x))
        return residual + self.dropout(delta)

