def masked_logsumexp(x, mask, dim, keepdim):
    # x: [B, Tv, Tt], mask: same shape (1 for valid, 0 for padded)
    # substitute -inf where mask=0 so those positions don't contribute
    neg_inf = torch.finfo(x.dtype).min
    x_masked = torch.where(mask > 0, x, torch.full_like(x, neg_inf))
    return torch.logsumexp(x_masked, dim=dim, keepdim=keepdim)

def stable_sinkhorn_masked(mu, nu, cost, valid_mask, epsilon=0.2, n_iter=40):
    """Masked, numerically-stable batched Sinkhorn in log-space."""
    # work in float32 for stability
    mu   = mu.float()
    nu   = nu.float()
    cost = cost.float()
    M    = valid_mask.float()

    # guard: ensure each valid row/col has at least one valid partner
    # (rare, but can happen if a sample is empty after masking)
    row_has_valid = (M.sum(dim=2, keepdim=True) > 0).float()
    col_has_valid = (M.sum(dim=1, keepdim=True) > 0).float()
    M = M * row_has_valid * col_has_valid

    # duals
    u = torch.zeros_like(mu)
    v = torch.zeros_like(nu)

    for _ in range(n_iter):
        # u update: log mu - logsumexp_j [ (-C + v)/eps ] over valid j
        lse_v = masked_logsumexp((-cost + v) / epsilon, M, dim=2, keepdim=True)
        u = epsilon * (torch.log(mu + 1e-8) - lse_v) + u
        u = torch.nan_to_num(u, nan=0.0, posinf=0.0, neginf=0.0)

        # v update: log nu - logsumexp_i [ (-C + u)/eps ] over valid i
        lse_u = masked_logsumexp((-cost + u) / epsilon, M, dim=1, keepdim=True)
        v = epsilon * (torch.log(nu + 1e-8) - lse_u) + v
        v = torch.nan_to_num(v, nan=0.0, posinf=0.0, neginf=0.0)

    # transport plan: exp( (-C + u + v)/eps ), zero outside mask
    pi = torch.exp((-cost + u + v) / epsilon)
    pi = torch.where(M > 0, pi, torch.zeros_like(pi))
    pi = torch.nan_to_num(pi, nan=0.0, posinf=0.0, neginf=0.0)
    return pi


