    def _forward_sinkhorn(self, inputs_of_experts, tgt_input, input_attention_mask,
                        epsilon=0.2, n_iter=40):
        """Sinkhorn OT alignment (batched, masked, stable)."""
        # 1) Fuse experts
        globals = [exp['x_global'] for exp in inputs_of_experts]
        x_global = torch.cat(globals, dim=-1)
        expert_outputs = [exp['encoder_embeds'] for exp in inputs_of_experts]
        fused_embeds, _, _ = self.topk_gating(x_global, expert_outputs)  # [B, Tv, H]
        video_embeds = fused_embeds
        video_mask   = input_attention_mask.float()  # [B, Tv]

        # 2) Text tokens + mask
        text_embeds = tgt_input["text_embeddings"].to(video_embeds.device)
        text_mask   = tgt_input["text_mask"].to(video_embeds.device).float()

        # 3) Encode video with mT5 encoder (optional but recommended)
        video_out = self.mt5_model.encoder(
            inputs_embeds=video_embeds,
            attention_mask=video_mask.long(),
            return_dict=True,
        )
        video_tokens = video_out.last_hidden_state  # [B, Tv, H]

        # 4) Normalize in float32
        # (also clamp norms to avoid zero-norm vectors)
        def safe_norm(x):
            x = x.float()
            x = x / (x.norm(dim=-1, keepdim=True).clamp_min(1e-6))
            return x
        video_tokens = safe_norm(video_tokens)
        text_embeds  = safe_norm(text_embeds)

        # 5) Build masked cosine distance
        # cost in [0,2], finite only on valid pairs
        sim  = torch.bmm(video_tokens, text_embeds.transpose(1, 2))       # [B, Tv, Tt]
        cost = torch.clamp(1.0 - sim, 0.0, 2.0)

        mask_v = video_mask.unsqueeze(-1)  # [B, Tv, 1]
        mask_t = text_mask.unsqueeze(1)    # [B, 1, Tt]
        valid  = (mask_v * mask_t) > 0     # [B, Tv, Tt], bool

        # set cost to +inf where invalid, so they never contribute
        cost = torch.where(valid, cost, torch.full_like(cost, float('inf')))

        # 6) Uniform marginals on valid tokens
        mu = mask_v / (mask_v.sum(dim=1, keepdim=True) + 1e-8)  # [B, Tv, 1]
        nu = mask_t / (mask_t.sum(dim=2, keepdim=True) + 1e-8)  # [B, 1, Tt]

        # 7) Sinkhorn (masked, stable)
        pi = stable_sinkhorn_masked(mu, nu, cost, valid, epsilon=epsilon, n_iter=n_iter)

        # 8) OT loss: masked average
        # Replace inf cost by 0 for multiplication (will be masked by pi anyway)
        cost_finite = torch.where(torch.isinf(cost), torch.zeros_like(cost), cost)
        denom = valid.float().sum(dim=[1,2]).clamp_min(1.0)  # avoid /0
        loss_per_sample = (pi * cost_finite).sum(dim=[1,2]) / denom
        loss_ot = loss_per_sample.mean()

        # Optional debug: masked mean cost and pi mean only over valid pairs
        with torch.no_grad():
            valid_cost_mean = (cost_finite * valid.float()).sum() / denom.sum()
            pi_mean = (pi * valid.float()).sum() / denom.sum()
            if torch.isnan(loss_ot) or loss_ot.item() == 0.0 or torch.isinf(loss_ot):
                print("[Sinkhorn Debug] eps=", float(epsilon),
                    " n_iter=", n_iter,
                    " masked_cost_mean=", float(valid_cost_mean),
                    " pi_mean=", float(pi_mean))

        return {"sinkhorn_loss": loss_ot, "loss": loss_ot}
    
